# This file goes over the basic Hello World program in Python simply.
#
#  # # # # KEY # # # #
#
# Python does not need any imports, class declarations, or main functions
# just to print text. It is one of the simplest languages to get started with.
#
# print()   - prints text to the console followed by a new line.
#             Equivalent to printf("Hello, World!\n") in C
#             and Console.WriteLine("Hello, World!") in C#.
#
# #         - single-line comment. Everything after # on that line is ignored.
#             Equivalent to // in C and C#.
#
# No semicolons - Python does not use semicolons at the end of statements.
#
# No curly braces - Python uses indentation (spaces/tabs) to define blocks
#                   of code instead of { } like C and C#.
#
# No main() required - Python runs code top to bottom. However, the
#                      if __name__ == "__main__": pattern is commonly used
#                      to mark the entry point (see simple-functions.py).
#

# Print Hello World to the console
print("Hello, World!")
